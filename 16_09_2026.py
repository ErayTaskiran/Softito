class Araba:
    def __init__(self, marka, model, hiz):
        self.marka = marka
        self.model = model
        self.hiz = hiz

    def hizlandir(self, artis):
        self.hiz += artis

    def bilgi_goster(self):
        print("Marka:", self.marka)
        print("Model:", self.model)
        print("Hız:", self.hiz, "km/s")


