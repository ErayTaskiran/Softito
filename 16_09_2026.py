class Dikdortgen:
    def __init__(self, uzunluk, genislik):
        self.uzunluk = uzunluk
        self.genislik = genislik

    def alan_hesapla(self):
        return self.uzunluk * self.genislik

    def cevre_hesapla(self):
        return 2 * (self.uzunluk + self.genislik)


dikdortgen1 = Dikdortgen(10, 5)

print("Alan:", dikdortgen1.alan_hesapla())
print("Çevre:", dikdortgen1.cevre_hesapla())

class Kitap:
    def __init__(self, ad, yazar, sayfa_sayisi):
        self.ad = ad
        self.yazar = yazar
        self.sayfa_sayisi = sayfa_sayisi

    def ozet(self):
        return self.ad + " - " + self.yazar + " (" + str(self.sayfa_sayisi) + " sayfa)"


